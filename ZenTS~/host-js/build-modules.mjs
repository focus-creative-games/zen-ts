import fs from 'node:fs';
import {createRequire} from 'node:module';
const [input,output,toolchain]=process.argv.slice(2);
const require=createRequire(toolchain+'/package.json');
const {transformSync}=require('esbuild');
const ts=require('typescript');
const {modules,scripts=[]}=JSON.parse(fs.readFileSync(input,'utf8').replace(/^\uFEFF/,''));
// Source keys are encoded so downstream SDK text rewrites (e.g. console.log
// to out) cannot mutate an identity key while leaving packaged TextAssets intact.
const sourceKey=source=>{let key='';for(let i=0;i<source.length;i++)key+=source.charCodeAt(i).toString(16).padStart(4,'0');return key;};
const names=[],sources=[],seen=new Set();
for(const m of modules){
 const source=m.source.replace(/\r\n/g,'\n');
 const syntax=ts.createSourceFile(m.name,source,ts.ScriptTarget.Latest,true,ts.ScriptKind.JS);
 const check=node=>{if((ts.isCallExpression(node)&&node.expression.kind===ts.SyntaxKind.ImportKeyword)||(ts.isMetaProperty(node)&&node.keywordToken===ts.SyntaxKind.ImportKeyword))throw Error('HostJs modules must be preloaded; dynamic import/import.meta is not supported: '+m.name);ts.forEachChild(node,check);};check(syntax);
 const body=transformSync(source,{format:'cjs',target:'es2021',sourcefile:m.name,loader:'js'}).code;
 const factory='function(require,module,exports,CSharp,zents,console,globalThis){"use strict";\n'+body+'\n}';
 names.push(JSON.stringify(m.name)+':'+factory);
 if(!seen.has(source)){seen.add(source);sources.push(JSON.stringify(sourceKey(source))+':'+factory);}
}
const globals=scripts.map(script=>{
 const source=script.source.replace(/\r\n/g,'\n');
 const body=transformSync(source,{target:'es2021',loader:'js',sourcefile:script.name}).code;
 return JSON.stringify(sourceKey(source))+':function(globalThis){"use strict";var zents=globalThis.zents||(globalThis.zents={});\n'+body+'\n}';
});
const code="Module['ZenTSHostModules']={"+names.join(',')+"};Module['ZenTSHostSources']={"+sources.join(',')+"};Module['ZenTSHostScripts']={"+globals.join(',')+"};";
fs.writeFileSync(output,'// Generated by ZenTS. Do not edit.\nmergeInto(LibraryManager.library, {$ZenTSModules: {},$ZenTSModules__postset:'+JSON.stringify(code)+',zents_host_modules__deps:["$ZenTSModules"],zents_host_modules:function(){}});\n');
console.log('HostJs modules compiled:',modules.length);
